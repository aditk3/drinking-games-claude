/**
 * Prompt content for the built-in games. Adults only: "spicy" items are about sex, dating and
 * drunk stories. Rooms can switch to tame mode, which filters those out.
 * {player} in a dare is replaced with another player's name. Every dare can be refused for drinks.
 */

export type Prompt = { text: string; spicy?: boolean }
export type Pair = { a: string; b: string; spicy?: boolean }
export type Spice = 'spicy' | 'tame'

const t = (text: string): Prompt => ({ text })
const s = (text: string): Prompt => ({ text, spicy: true })

export function pool<T extends { spicy?: boolean }>(list: T[], spice: Spice): T[] {
  return spice === 'spicy' ? list : list.filter((x) => !x.spicy)
}

